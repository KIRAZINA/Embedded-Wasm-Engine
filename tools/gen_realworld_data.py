#!/usr/bin/env python3
"""tools/gen_realworld_data.py -- generate the real-world data headers.

Writes:
  realworld/matmul_data.h  : the 8x8 f32 matrices (values are multiples of
                             0.25, so every product and partial sum is
                             exact in binary32)
  realworld/crc32_table.h  : the 256-entry CRC-32 lookup table

Both files are committed: the generated data is part of the real-world
corpus and must not change silently. Re-run this script and diff the
result when the inputs change.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "realworld"))


def fmt_matrix(values, per_line=8):
    """Format a macro body: every line but the last ends with a backslash."""
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append("    " + ", ".join("%.2ff" % v for v in chunk) + ",")
    return " \\\n".join(lines)


def gen_matmul():
    # Multiples of 0.25 in [-2, 2]: exact in binary32.
    a = [((i * 7) % 17 - 8) * 0.25 for i in range(64)]
    b = [((i * 5 + 3) % 19 - 9) * 0.25 for i in range(64)]
    body = (
        "/* Generated by tools/gen_realworld_data.py -- do not edit. */\n"
        "#ifndef REALWORLD_MATMUL_DATA_H\n"
        "#define REALWORLD_MATMUL_DATA_H\n\n"
        "#define MATMUL_A { \\\n%s \\\n}\n\n"
        "#define MATMUL_B { \\\n%s \\\n}\n\n"
        "#endif /* REALWORLD_MATMUL_DATA_H */\n"
    ) % (fmt_matrix(a), fmt_matrix(b))
    with open(os.path.join(OUT, "matmul_data.h"), "w", encoding="utf-8") as fh:
        fh.write(body)
    return a, b


def gen_crc_table():
    table = []
    for i in range(256):
        crc = i
        for _ in range(8):
            crc = (crc >> 1) ^ (0xEDB88320 & -(crc & 1))
        table.append(crc & 0xFFFFFFFF)
    lines = []
    for i in range(0, 256, 4):
        chunk = table[i:i + 4]
        lines.append("    " + ", ".join("0x%08Xu" % v for v in chunk) + ",")
    body = (
        "/* Generated by tools/gen_realworld_data.py -- do not edit. */\n"
        "#ifndef REALWORLD_CRC32_TABLE_H\n"
        "#define REALWORLD_CRC32_TABLE_H\n\n"
        "/* CRC-32 (IEEE 802.3, reflected, polynomial 0xEDB88320) */\n"
        "static const unsigned int kCrcTable[256] = {\n%s\n};\n\n"
        "#endif /* REALWORLD_CRC32_TABLE_H */\n"
    ) % "\n".join(lines)
    with open(os.path.join(OUT, "crc32_table.h"), "w", encoding="utf-8") as fh:
        fh.write(body)
    return table


def main():
    a, b = gen_matmul()
    table = gen_crc_table()
    # self-check: the table must reproduce the standard CRC-32 of the
    # canonical test vector "123456789" (0xCBF43926).
    msg = b"123456789"
    crc = 0xFFFFFFFF
    for byte in msg:
        crc = table[(crc ^ byte) & 0xFF] ^ (crc >> 8)
    crc ^= 0xFFFFFFFF
    if crc != 0xCBF43926:
        print("ERROR: CRC-32 table self-check failed: 0x%08X" % crc)
        return 1
    print("crc32 table self-check: crc32('123456789') = 0x%08X (ok)" % crc)
    print("matmul A[0:4]=%s B[0:4]=%s" % (a[:4], b[:4]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
