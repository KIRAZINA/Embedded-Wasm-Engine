#!/usr/bin/env python3
"""Cross-reference MVP opcodes against enum, VM dispatch, validator, and tests.

Stdlib only. Default output: docs/OPCODE_MATRIX.md
Exit 0 unless --strict and any canonical opcode verdict is not OK.
"""
from __future__ import annotations

import argparse
import csv
import os
import re
import sys

# Resolve the repository root from this file's location. The path is
# normalised first: the tool is invoked with mixed separators on some
# platforms (for example "tools\opcode_matrix.py" under a POSIX shell),
# and os.path.dirname() does not split those reliably.
_ROOT = os.path.dirname(os.path.dirname(os.path.realpath(os.path.abspath(__file__))))
ROOT = _ROOT
CSV_PATH = os.path.join(ROOT, "tools", "mvp_opcodes.csv")
TYPES_H = os.path.join(ROOT, "include", "wasm_types.h")
VM_C = os.path.join(ROOT, "src", "wasm_vm.c")
VAL_C = os.path.join(ROOT, "src", "wasm_validate.c")
TESTS = os.path.join(ROOT, "tests")
DEFAULT_OUT = os.path.join(ROOT, "docs", "OPCODE_MATRIX.md")

ENUM_RE = re.compile(
    r"\bOP_([A-Z0-9_]+)\s*=\s*0x([0-9A-Fa-f]+)\b"
)
CASE_OP_RE = re.compile(r"\bcase\s+OP_([A-Z0-9_]+)\s*:")
CASE_HEX_RE = re.compile(r"\bcase\s+0x([0-9A-Fa-f]+)u?\s*:")
WORDY = frozenset(
    {
        "if",
        "else",
        "end",
        "block",
        "loop",
        "br",
        "return",
        "call",
        "nop",
        "drop",
        "select",
    }
)


def read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def load_csv(path: str) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    with open(path, encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            hx = row["hex"].strip().lower()
            name = row["name"].strip()
            rows.append((hx, name))
    return rows


def extract_enum(src: str) -> dict[int, str]:
    return {int(hx, 16): name for name, hx in ENUM_RE.findall(src)}


def extract_vm_ops(src: str) -> set[str]:
    marker = "wasm_trap_t wasm_vm_step("
    start = src.find(marker)
    if start < 0:
        return set()
    body = src[start:]
    nxt = body.find("\nwasm_trap_t ", 1)
    if nxt > 0:
        body = body[:nxt]
    return set(CASE_OP_RE.findall(body))


def extract_validator_hex(src: str) -> tuple[set[int], bool]:
    marker = "while (p < body_end)"
    start = src.find(marker)
    if start < 0:
        return set(), False
    body = src[start:]
    end = body.find("func_end:")
    if end > 0:
        body = body[:end]
    ops = {int(hx, 16) for hx in CASE_HEX_RE.findall(body)}
    has_default = "default:" in body
    return ops, has_default


def load_tests() -> str:
    chunks: list[str] = []
    for dirpath, _, files in os.walk(TESTS):
        for name in files:
            if name.endswith((".c", ".h", ".txt", ".md")):
                chunks.append(read(os.path.join(dirpath, name)))
    return "\n".join(chunks)


def mnemonic_hit(blob: str, name: str) -> bool:
    if name == "call":
        return re.search(r"(?<![\w.])call(?!_indirect)", blob) is not None
    if name == "i32.eq":
        return re.search(r"(?<![\w.])i32\.eq(?![zu\w])", blob) is not None
    if name == "br":
        return re.search(r"(?<![\w.])br(?!_)", blob) is not None
    if "." in name:
        return name in blob
    if name in WORDY:
        return bool(re.search(r"(?<![\w.])" + re.escape(name) + r"(?![\w.])", blob))
    return name in blob


def tested_for(blob: str, hx: str, name: str, enum_name: str | None) -> bool:
    if mnemonic_hit(blob, name):
        return True
    if enum_name and ("OP_" + enum_name) in blob:
        return True
    # Prefer the C suffix form so wasm magic 0x00 / version 0x01 are not the
    # only signal; still accept 0xHH when the mnemonic is unique.
    pat_u = re.compile(r"0x0*" + hx + r"u\b", re.I)
    if pat_u.search(blob) and name not in ("unreachable", "nop", "f64.eq"):
        # 0x00u/0x01u/0x61u appear in every module header fixture.
        if hx in ("00", "01", "61"):
            return False
        return True
    return False


def verdict(in_enum: bool, in_vm: bool, in_val: bool, tested: bool) -> str:
    if not in_enum:
        return "NOT_IN_ENUM"
    if not in_vm:
        return "MISSING_IN_VM"
    if not in_val:
        return "MISSING_IN_VALIDATOR"
    if not tested:
        return "UNTESTED"
    return "OK"


def yn(flag: bool) -> str:
    return "yes" if flag else "no"


def emit_md(rows: list[dict], default_rejects: bool, out_path: str) -> None:
    counts: dict[str, int] = {}
    for row in rows:
        counts[row["verdict"]] = counts.get(row["verdict"], 0) + 1
    lines = [
        "# MVP opcode coverage matrix",
        "",
        "Generated by `tools/opcode_matrix.py` from `tools/mvp_opcodes.csv`,",
        "`include/wasm_types.h`, `src/wasm_vm.c` (`wasm_vm_step` switch),",
        "`src/wasm_validate.c` (`vfunc_body` instruction switch), and `tests/`.",
        "",
        "## Verdict priority",
        "",
        "`NOT_IN_ENUM` > `MISSING_IN_VM` > `MISSING_IN_VALIDATOR` > `UNTESTED` > `OK`.",
        "",
        "## Reserved / non-canonical bytes",
        "",
        "Bytes **not** in the canonical MVP list are invalid in this subset.",
        "The validator instruction `default:` branch "
        + ("**is present**" if default_rejects else "**is missing**")
        + " in `vfunc_body` and returns `WASM_ERR_INVALID_SECTION`",
        "(comment names nop, drop, i64 comparisons, sub-word/float memory,",
        "saturating conversions, and other undecodable bytes).",
        "The VM `wasm_vm_step` switch `default:` returns",
        "`WASM_TRAP_UNKNOWN_OPCODE`. `vm_scan_block` also returns",
        "`WASM_TRAP_UNKNOWN_OPCODE` for bytes it cannot skip.",
        "",
        "## Counts",
        "",
        "| verdict | count |",
        "|---|---:|",
    ]
    for key in (
        "OK",
        "UNTESTED",
        "MISSING_IN_VALIDATOR",
        "MISSING_IN_VM",
        "NOT_IN_ENUM",
    ):
        lines.append("| %s | %d |" % (key, counts.get(key, 0)))
    lines.extend(
        [
            "",
            "## Matrix",
            "",
            "| hex | name | in enum | in VM switch | in validator | tested | verdict |",
            "|---|---|---|---|---|---|---|",
        ]
    )
    for row in rows:
        lines.append(
            "| %s | %s | %s | %s | %s | %s | %s |"
            % (
                row["hex"],
                row["name"],
                yn(row["in_enum"]),
                yn(row["in_vm"]),
                yn(row["in_val"]),
                yn(row["tested"]),
                row["verdict"],
            )
        )
    lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--strict", action="store_true")
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--csv", default=CSV_PATH)
    ns = parser.parse_args(argv)

    canonical = load_csv(ns.csv)
    enum_map = extract_enum(read(TYPES_H))
    vm_ops = extract_vm_ops(read(VM_C))
    val_ops, default_rejects = extract_validator_hex(read(VAL_C))
    tests_blob = load_tests()

    rows: list[dict] = []
    non_ok: list[str] = []
    for hx, name in canonical:
        code = int(hx, 16)
        enum_name = enum_map.get(code)
        in_enum = enum_name is not None
        in_vm = bool(enum_name) and enum_name in vm_ops
        in_val = code in val_ops
        tested = tested_for(tests_blob, hx, name, enum_name)
        v = verdict(in_enum, in_vm, in_val, tested)
        rows.append(
            {
                "hex": hx,
                "name": name,
                "in_enum": in_enum,
                "in_vm": in_vm,
                "in_val": in_val,
                "tested": tested,
                "verdict": v,
            }
        )
        if v != "OK":
            non_ok.append("%s %s %s" % (hx, name, v))

    emit_md(rows, default_rejects, ns.out)
    sys.stderr.write(
        "opcode_matrix: %d canonical, %d non-OK, wrote %s\n"
        % (len(rows), len(non_ok), ns.out)
    )
    if ns.strict and non_ok:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
